<#
.SYNOPSIS
	Regenerates docs\FUNCTIONS.md - every MiniGhost function: category, file, what it does (first
	sentence of its header description) and which functions / GUI files call it.

.DESCRIPTION
	Reads src\Functions\<Category>\*.ps1 (one function per file) plus the Bootstrap, Main and GUI
	files. Run by Build.ps1 after every successful build; can also be run on its own.
#>
[CmdletBinding()]
param ()

$ErrorActionPreference = 'Stop'
$projectRoot = Split-Path -Parent $PSScriptRoot
$srcRoot = Join-Path $projectRoot 'src'
$outFile = Join-Path $projectRoot 'docs\FUNCTIONS.md'
$categoryOrder = @('UI', 'Store', 'Sql', 'System', 'Workflow')
$categoryText = @{
	UI       = 'Dialogs, message boxes, labels and the shared operation-status table.'
	Store    = 'Store number, store name, machine-name rules and every INI file MiniGhost rewrites.'
	Sql      = 'Database connection and the SQL updates (store number, machine name, truncation).'
	System   = 'Network, registry, X*/Z* folder and temp-file housekeeping on this machine.'
	Workflow = 'The multi-step rename / sync flows the buttons start.'
}

function Get-Description([string[]]$Lines)
{
	$inDesc = $false
	$parts = New-Object System.Collections.Generic.List[string]
	foreach ($l in $Lines)
	{
		if ($l -match '^\s*function\s') { break }
		if ($l -match '^#\s*Description:') { $inDesc = $true; continue }
		if (-not $inDesc) { continue }
		$t = ($l -replace '^#\s*', '').Trim()
		if (-not $t -or $t -match '^[=-]{5,}$' -or $t -match '^\w[\w ]*:$') { if ($parts.Count) { break } else { continue } }
		$parts.Add($t)
	}
	$text = ($parts -join ' ')
	$m = [regex]::Match($text, '^.+?[.!](?=\s|$)')
	if ($m.Success -and $m.Length -ge 40) { $text = $m.Value }
	if ($text.Length -gt 180) { $text = $text.Substring(0, 177).TrimEnd() + '...' }
	return $text
}

# Every source file, keyed by its path relative to src (forward slashes)
$allFiles = @(Get-ChildItem -Path $srcRoot -Recurse -File -Filter '*.ps1')
$texts = @{ }
foreach ($f in $allFiles)
{
	$rel = $f.FullName.Substring($srcRoot.Length + 1).Replace('\', '/')
	$texts[$rel] = [System.IO.File]::ReadAllText($f.FullName)
}
$relNames = [string[]]@($texts.Keys)
[Array]::Sort($relNames, [StringComparer]::OrdinalIgnoreCase)

$sb = New-Object System.Text.StringBuilder
[void]$sb.Append("# MiniGhost - function index`r`n`r`n")
[void]$sb.Append("Generated by ``build\Update-FunctionIndex.ps1`` (run by ``Build.ps1``) - do not edit by hand.`r`n")
[void]$sb.Append("One function per file under ``src\Functions\<Category>``.`r`n")

foreach ($cat in $categoryOrder)
{
	$catDir = Join-Path $srcRoot ('Functions\' + $cat)
	if (-not (Test-Path -LiteralPath $catDir)) { continue }
	$names = [string[]]@(Get-ChildItem -Path $catDir -File -Filter '*.ps1' | ForEach-Object { $_.BaseName })
	[Array]::Sort($names, [StringComparer]::OrdinalIgnoreCase)

	[void]$sb.Append("`r`n## $cat`r`n`r`n" + $categoryText[$cat] + "`r`n`r`n")
	[void]$sb.Append("| Function | What it does | Called from |`r`n|---|---|---|`r`n")
	foreach ($name in $names)
	{
		$selfRel = "Functions/$cat/$name.ps1"
		$desc = Get-Description ($texts[$selfRel] -split "`r?`n")
		$pattern = '(?<![\w-])' + [regex]::Escape($name) + '(?![\w-])'
		$callers = New-Object System.Collections.Generic.List[string]
		foreach ($rel in $relNames)
		{
			if ($rel -eq $selfRel) { continue }
			if ([regex]::IsMatch($texts[$rel], $pattern))
			{
				$leaf = $rel.Substring($rel.LastIndexOf('/') + 1) -replace '\.ps1$', ''
				if ($rel.StartsWith('Functions/')) { $callers.Add($leaf) }
				else { $callers.Add($rel.Substring(0, $rel.IndexOf('/')) + '/' + $leaf) }
			}
		}
		$callerText = if ($callers.Count) { $callers -join ', ' } else { '-' }
		[void]$sb.Append("| ``$name`` | $desc | $callerText |`r`n")
	}
}

[System.IO.File]::WriteAllText($outFile, $sb.ToString(), [System.Text.Encoding]::ASCII)
